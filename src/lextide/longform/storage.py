"""Durable local JSON, locks and independently verified raw PCM cache entries."""

import contextlib
import fcntl
import hashlib
import json
import os
import re
import shutil
import stat
import tempfile
from pathlib import Path

from ..engines.base import SentenceBoundary
from ..errors import StudioError, ValidationError
from ..subtitles import prepare_subtitles

_BLOCK = 1024 * 1024
_MAX_JSON = 16 * 1024 * 1024
_MAX_PCM_BYTES = 24_000 * 600 * 2 + 65_536
_KEY = re.compile(r"[a-f0-9]{64}")


def _io_error() -> StudioError:
    return StudioError("STORAGE_IO", "Cannot safely access task or cache storage.", 6)


def _json_bytes(value: dict) -> bytes:
    if not isinstance(value, dict):
        raise ValidationError("Stored JSON must be an object.")

    def check_keys(item):
        if isinstance(item, dict):
            if any(not isinstance(key, str) for key in item):
                raise ValidationError("JSON object keys must be strings.")
            for child in item.values():
                check_keys(child)
        elif isinstance(item, list):
            for child in item:
                check_keys(child)
        elif item is not None and type(item) not in (str, int, float, bool):
            raise ValidationError("Stored values must be JSON data.")

    try:
        check_keys(value)
        return json.dumps(
            value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeError, RecursionError):
        raise ValidationError("Stored values must be finite UTF-8 JSON data.") from None


def canonical_key(request: dict) -> str:
    """Hash the complete raw synthesis request, independent of generated bytes."""
    return hashlib.sha256(_json_bytes(request)).hexdigest()


def _absolute(path: Path) -> Path:
    path = Path(path).expanduser()
    if not path.is_absolute():
        path = Path.cwd() / path
    # Check before collapsing '..': a symlink component must not disappear.
    for ancestor in reversed((path, *path.parents)):
        if ancestor.is_symlink():
            raise _io_error()
    return Path(os.path.abspath(path))


def safe_directory(path: Path, create: bool = False) -> Path:
    """Return an absolute path, refusing symlinks in every existing component."""
    try:
        path = _absolute(path)
        for ancestor in reversed((path, *path.parents)):
            try:
                info = ancestor.lstat()
            except FileNotFoundError:
                if not create:
                    continue
                ancestor.mkdir(mode=0o700)
                info = ancestor.lstat()
            if not stat.S_ISDIR(info.st_mode):
                raise _io_error()
        return path
    except OSError:
        raise _io_error() from None


def _safe_file(path: Path) -> Path:
    path = _absolute(path)
    safe_directory(path.parent)
    try:
        info = path.lstat()
    except FileNotFoundError:
        return path
    if not stat.S_ISREG(info.st_mode):
        raise _io_error()
    return path


def _open_read(path: Path):
    path = _safe_file(path)
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            raise _io_error()
        return os.fdopen(descriptor, "rb")
    except BaseException:
        os.close(descriptor)
        raise


def file_sha256(path: Path) -> str:
    """Hash a regular local file with bounded memory and no symlink following."""
    digest = hashlib.sha256()
    try:
        with _open_read(path) as stream:
            for block in iter(lambda: stream.read(_BLOCK), b""):
                digest.update(block)
        return digest.hexdigest()
    except OSError:
        raise _io_error() from None


def _sync_directory(path: Path) -> None:
    path = safe_directory(path)
    descriptor = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def atomic_json(path: Path, value: dict) -> None:
    """Publish a complete private JSON file via same-directory replace and fsync."""
    body = _json_bytes(value) + b"\n"
    temporary = None
    try:
        path = _absolute(path)
        safe_directory(path.parent, create=True)
        _safe_file(path)
        descriptor, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
        temporary = Path(name)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(body)
            stream.flush()
            os.fsync(stream.fileno())
        _safe_file(path)
        os.replace(temporary, path)
        temporary = None
        _sync_directory(path.parent)
    except OSError:
        raise _io_error() from None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def read_json(path: Path, max_bytes: int = _MAX_JSON) -> dict:
    """Read a bounded object, rejecting duplicate keys, NaN and unsafe paths."""
    if type(max_bytes) is not int or max_bytes <= 0:
        raise ValidationError("JSON size limit must be a positive integer.")

    def object_pairs(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError("duplicate JSON key")
            result[key] = value
        return result

    def invalid_constant(_):
        raise ValueError("non-finite JSON value")

    try:
        with _open_read(path) as stream:
            if os.fstat(stream.fileno()).st_size > max_bytes:
                raise ValidationError("Stored JSON exceeds its size limit.")
            body = stream.read(max_bytes + 1)
        if len(body) > max_bytes:
            raise ValidationError("Stored JSON exceeds its size limit.")
        value = json.loads(
            body.decode("utf-8"), object_pairs_hook=object_pairs, parse_constant=invalid_constant
        )
        _json_bytes(value)
        return value
    except (ValueError, UnicodeError, RecursionError):
        raise ValidationError("Stored JSON is invalid.") from None
    except OSError:
        raise _io_error() from None


@contextlib.contextmanager
def exclusive_lock(path: Path):
    """Hold a safe regular-file flock; a competing process fails immediately."""
    descriptor = None
    try:
        path = _absolute(path)
        safe_directory(path.parent, create=True)
        _safe_file(path)
        descriptor = os.open(path, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW | os.O_NONBLOCK, 0o600)
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            raise _io_error()
        try:
            fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise StudioError("TASK_BUSY", "Task or cache is already in use.", 6) from None
        yield
    except OSError:
        raise _io_error() from None
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _validate_pcm(path: Path) -> dict:
    # media uses storage for hashes; importing at call time avoids a cycle.
    from .media import validate_pcm

    return validate_pcm(path)


def validate_chunk_metadata(metadata: dict, request: dict, wav: Path) -> None:
    """Check decoded PCM, native coverage and any pinned request model identity."""
    _json_bytes(metadata)
    pcm = _validate_pcm(wav)
    for field in ("samples", "sample_rate", "channels"):
        if type(metadata.get(field)) is not int or metadata[field] != pcm.get(field):
            raise ValidationError("Cached PCM metadata does not match decoded audio.")
    if (
        metadata["sample_rate"] != 24_000
        or metadata["channels"] != 1
        or not 0 < metadata["samples"] <= 24_000 * 600
        or not isinstance(metadata.get("timing_source"), str)
        or not metadata["timing_source"].strip()
        or "model" not in metadata
        or (metadata["model"] is not None and not isinstance(metadata["model"], dict))
        or not isinstance(metadata.get("effective_settings"), dict)
        or not isinstance(request.get("text"), str)
    ):
        raise ValidationError("Cached audio metadata is invalid.")
    engine = request.get("engine")
    if isinstance(engine, dict) and "model" in engine:
        if _json_bytes({"model": metadata["model"]}) != _json_bytes({"model": engine["model"]}):
            raise ValidationError("Chunk model metadata does not match the synthesis request.")
    boundaries = metadata.get("boundaries")
    if not isinstance(boundaries, list) or not boundaries:
        raise ValidationError("Cached audio has no native sentence boundaries.")
    if any(
        not isinstance(item, dict) or set(item) != {"offset_ticks", "duration_ticks", "text"}
        for item in boundaries
    ):
        raise ValidationError("Cached sentence boundaries are invalid.")
    prepare_subtitles(
        [SentenceBoundary(**item) for item in boundaries],
        audio_duration_ms=(metadata["samples"] * 1000 + 23_999) // 24_000,
        expected_text=request["text"],
        timing_source=metadata["timing_source"],
    )


def _safe_tree(path: Path) -> None:
    safe_directory(path)
    if not path.exists():
        return
    for parent, directories, files in os.walk(path, followlinks=False):
        for name in directories:
            safe_directory(Path(parent) / name)
        for name in files:
            _safe_file(Path(parent) / name)


def _remove_owned(path: Path) -> None:
    """Only delete an owned entry with recognized names and no symlink tree."""
    _safe_tree(path)
    if not path.exists():
        return
    for child in path.iterdir():
        if child.name not in {"audio.wav", "manifest.json"} and not re.fullmatch(
            r"\.manifest\.json\.[A-Za-z0-9_-]+\.tmp", child.name
        ):
            raise _io_error()
        if not child.is_file():
            raise _io_error()
    shutil.rmtree(path)
    _sync_directory(path.parent)


class Cache:
    """Raw chunk cache. Callers copy hits into their task while holding lock()."""

    def __init__(self, root: Path):
        self.root = safe_directory(root, create=True)
        self._held_keys: set[str] = set()
        try:
            descriptor = os.open(self.root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            try:
                os.fchmod(descriptor, 0o700)
            finally:
                os.close(descriptor)
            safe_directory(self.root / ".locks", create=True)
            safe_directory(self.root / ".staging", create=True)
        except OSError:
            raise _io_error() from None

    @staticmethod
    def _key(key: str) -> None:
        if not isinstance(key, str) or not _KEY.fullmatch(key):
            raise ValidationError("Cache key must be a canonical SHA256 value.")

    @contextlib.contextmanager
    def lock(self, key: str):
        self._key(key)
        with exclusive_lock(self.root / ".locks" / f"{key}.lock"):
            self._held_keys.add(key)
            try:
                _remove_owned(self.root / ".staging" / key)
                yield
            finally:
                self._held_keys.discard(key)

    def load(self, key: str, request: dict) -> dict | None:
        """Validate every byte and native timing before reporting a complete hit."""
        try:
            self._key(key)
            if canonical_key(request) != key:
                return None
            directory = self.root / key
            _safe_tree(directory)
            manifest = read_json(directory / "manifest.json")
            if (
                type(manifest.get("schema_version")) is not int
                or manifest["schema_version"] != 1
                or manifest.get("status") != "complete"
                or manifest.get("cache_key") != key
                or canonical_key(manifest.get("request")) != key
                or _json_bytes(manifest["request"]) != _json_bytes(request)
                or not isinstance(manifest.get("artifact_sha256"), str)
                or not _KEY.fullmatch(manifest["artifact_sha256"])
            ):
                return None
            wav = _safe_file(directory / "audio.wav")
            if (
                type(manifest.get("bytes")) is not int
                or manifest["bytes"] <= 0
                or wav.stat().st_size != manifest["bytes"]
                or file_sha256(wav) != manifest["artifact_sha256"]
            ):
                return None
            validate_chunk_metadata(manifest.get("metadata"), request, wav)
            return {
                "path": str(wav),
                "metadata": manifest["metadata"],
                "artifact_sha256": manifest["artifact_sha256"],
                "cache_key": key,
            }
        except (StudioError, OSError, TypeError, ValueError, KeyError, RecursionError):
            return None

    def publish(self, key: str, request: dict, wav: Path, metadata: dict) -> dict:
        """Copy then atomically publish a verified directory under a held key lock."""
        self._key(key)
        if key not in self._held_keys:
            raise StudioError("STORAGE_IO", "Publishing a cache entry requires its lock.", 6)
        if canonical_key(request) != key:
            raise ValidationError("Cache key does not match the synthesis request.")
        cached = self.load(key, request)
        if cached is not None:
            return cached
        staging, destination = self.root / ".staging" / key, self.root / key
        try:
            _remove_owned(staging)
            safe_directory(staging, create=True)
            target = staging / "audio.wav"
            with _open_read(wav) as source:
                source_bytes = os.fstat(source.fileno()).st_size
                if not 0 < source_bytes <= _MAX_PCM_BYTES:
                    raise ValidationError("Raw PCM file exceeds the chunk size limit.")
                descriptor = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
                with os.fdopen(descriptor, "wb") as output:
                    remaining = source_bytes
                    while remaining:
                        block = source.read(min(_BLOCK, remaining))
                        if not block:
                            raise ValidationError("Raw PCM source changed during copying.")
                        output.write(block)
                        remaining -= len(block)
                    if source.read(1):
                        raise ValidationError("Raw PCM source changed during copying.")
                    output.flush()
                    os.fsync(output.fileno())
            validate_chunk_metadata(metadata, request, target)
            manifest = {
                "schema_version": 1,
                "status": "complete",
                "cache_key": key,
                "request": request,
                "artifact_sha256": file_sha256(target),
                "bytes": target.stat().st_size,
                "metadata": metadata,
            }
            atomic_json(staging / "manifest.json", manifest)
            _sync_directory(staging)
            _remove_owned(destination)
            os.replace(staging, destination)
            _sync_directory(self.root)
            _sync_directory(self.root / ".staging")
            result = self.load(key, request)
            if result is None:
                raise ValidationError("Published cache entry did not pass verification.")
            return result
        except OSError:
            raise _io_error() from None
